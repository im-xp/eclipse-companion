export function SocialRow({
  socials,
  className = "",
}: {
  socials?: SocialLink[];
  className?: string;
}) {
  if (!socials || socials.length === 0) return null;
  return (
    <div className={`flex flex-wrap items-center gap-2 ${className}`}>
      {socials.map((s) => {
        const label = LABELS[s.platform] ?? "Link";
        return (
          <a
            key={s.platform + s.href}
            href={s.href}
            target="_blank"
            rel="noreferrer"
            onClick={(e) => e.stopPropagation()}
            title={label}
            aria-label={label}
            className="flex size-8 items-center justify-center rounded-full border border-moon-white/15 text-moon-white/70 transition-colors hover:border-moon-white/40 hover:text-moon-white"
          >
            <svg viewBox="0 0 24 24" fill="currentColor" className="size-4">
              {ICONS[s.platform] ?? ICONS.website}
            </svg>
          </a>
        );
      })}
    </div>
  );
}
